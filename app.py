
from flask import Flask, request, jsonify, send_from_directory
from flask_cors import CORS
import os
import re
import psycopg
from pathlib import Path

app = Flask(__name__)

BASE_DIR = Path(__file__).resolve().parent

# Allow requests from your portfolio and local development.
CORS(app, resources={
    r"/api/*": {
        "origins": [
            "http://127.0.0.1:5000",
            "http://localhost:5000",
            "https://harshavardhanpolakala-ops.github.io"
        ]
    }
})


# Connect to Supabase and ensure the messages table exists.
def create_database():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is not configured")

    with psycopg.connect(database_url) as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL,
                message TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)


# Display the portfolio homepage locally.
@app.route("/")
def home():
    return send_from_directory(BASE_DIR, "index.html")


# Serve public website files locally.
@app.route("/style.css")
@app.route("/script.js")
def public_files():
    filename = request.path.lstrip("/")
    return send_from_directory(BASE_DIR, filename)


# Receive and save contact form messages.
@app.route("/api/contact", methods=["POST"])
def contact():
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({"error": "Invalid request"}), 400

    name = str(data.get("name", "")).strip()
    email = str(data.get("email", "")).strip()
    message = str(data.get("message", "")).strip()

    if not name or not email or not message:
        return jsonify({"error": "All fields are required"}), 400

    if len(name) > 100 or len(email) > 254 or len(message) > 5000:
        return jsonify({"error": "One or more fields are too long"}), 400

    if not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
        return jsonify({"error": "Please enter a valid email address"}), 400

    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        return jsonify({"error": "Database is not configured"}), 500

    try:
        with psycopg.connect(database_url) as connection:
            connection.execute(
                """
                INSERT INTO messages (name, email, message)
                VALUES (%s, %s, %s)
                """,
                (name, email, message)
            )

        return jsonify({
            "success": "Message received successfully!"
        }), 201

    except Exception:
        app.logger.exception("Could not save contact message")
        return jsonify({
            "error": "Unable to save your message. Please try again."
        }), 500


# Initialize the database when the application starts.
create_database()


if __name__ == "__main__":
    app.run(debug=False)
